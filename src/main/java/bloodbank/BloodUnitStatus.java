package bloodbank;

/** Этапы жизни одного пакета донорской крови. */
/** перечисление */
public enum BloodUnitStatus {

    /** Кровь взяли у донора, пакет зарегистрирован. */
    COLLECTED,

    /** Пакет отправлен на лабораторные анализы. */
    TESTED,

    /** Анализы отрицательные, пакет годен к выдаче. */
    RELEASED,

    /** Пакет выдан в больницу под пациента. */
    ISSUED,

    /** Брак по анализам или истёк срок годности — на утилизацию. */
    DISCARDED
}
